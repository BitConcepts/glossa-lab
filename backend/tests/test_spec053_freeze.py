def test_aee_hook_artifacts_record_the_pass():
    aee_dir = SPEC / "aee"
    note = (aee_dir / "freeze-aee-note.md").read_text(encoding="utf-8")
    assert "DD-053-19" in note
    assert "zero\ncorrectness failure modes" in note or (
        "zero correctness" in note
    )
    for phase in ("after_specify", "after_plan", "after_tasks"):
        artifacts = sorted(aee_dir.glob(f"aee-{phase}-*.json"))
        assert artifacts, phase
        assessment = json.loads(
            artifacts[0].read_text(encoding="utf-8")
        )
        assert assessment["phase"] == phase
        failures = [
            f
            for claim in assessment["claims"]
            for f in claim["failures"]
        ]
        assert failures, phase
        assert all(
            f["challenge"] == "Draft outcome cap" for f in failures
        ), phase
        scores = assessment["scores"]
        assert min(
            s["propagated_score"] for s in scores.values()
        ) >= 0.70


def test_cited_records_carry_the_design_facts():
    # The claim record's manual_001 facts, asserted on the
    # live file (the Spec 038 form: no live-file hash on
    # the regenerated claims store; the freeze-time hash
    # stands as the definition constant asserted above).
    claim_doc = json.loads(CLAIM_FILE.read_text(encoding="utf-8"))
    entries = {
        c["claim_id"]: c for c in claim_doc["claims"]
    }
    entry = entries[CLAIM_ID]
    assert entry["claim_status"] == "strongly_supported"
    assert entry["stage"] == "explained"
    assert entry["normalized_claim"] == (
        "Indus script sign frequencies follow a "
        "Zipf-Mandelbrot distribution."
    )
    assert entry["falsification_condition"] == (
        "If frequency distribution deviates from "
        "Zipf-Mandelbrot law."
    )
    assert entry["glossa_lab_evidence"] == (
        "Phase-43: V3 Zipf exponent ~1.35 (super-Zipfian) [VERIFIED]"
    )
    assert "not language at all" in entry["not_understood"]
    # The anchors census the strict population rests on.
    assert _sha(ANCHORS) == ANCHORS_SHA256
    anchors = json.loads(ANCHORS.read_text(encoding="utf-8"))["anchors"]
    assert len(anchors) == 287
    strict = [
        k
        for k, v in anchors.items()
        if v.get("validation_status") == "strict_sa_independent"
    ]
    assert len(strict) == 94
    # The crosswalks S2 rests on.
    assert _sha(CROSSWALK) == CROSSWALK_SHA256
    assert _sha(MP_CROSSWALK) == MP_CROSSWALK_SHA256
    # The Phase-43 record: pinned, and carrying no Zipf
    # fit - the ground for the DD-053-11 ruling.
    assert _sha(PHASE43) == PHASE43_SHA256
    phase43_text = PHASE43.read_text(encoding="utf-8")
    phase43 = json.loads(phase43_text)
    assert "zipf" not in phase43_text.lower()
    assert "mandelbrot" not in phase43_text.lower()
    assert phase43["T1_1_corpus_v3"] or phase43["experiment"]
