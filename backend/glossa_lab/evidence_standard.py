"""Spec 094 Stage 2 — the promotion evidence standard (C094-4, C094-5).

Promotion evidence is a pinned artifact of a registered class:

- **Pinning (C094-4).** An evidence artifact is pinned by content hash
  — SHA-256 computed at pin time and recorded on the candidate record
  (:func:`pin_evidence`). Promotion verifies the artifact's bytes
  against the recorded pin and refuses on absence or mismatch
  (:func:`evidence_pin_refusal`). A pin supplied only in the promote
  request is not a pin: gate inputs live on the record, never in the
  request that asks for the decision (C094-3's construction rule).
- **Registered classes (C094-5).** The admissible evidence classes are
  the registered list below (:data:`REGISTERED_EVIDENCE_CLASSES`) —
  the classes named in C094-5 as ratified at Stage 2. The list is a
  code-resident registered artifact: it is amended only by a recorded
  act (a change to this module, landed through review), never by
  configuration, environment, or request data. Artifacts generated by
  the loop or the anchor path about the candidate itself — pipeline
  outputs, staging and archive files, run syntheses — are not a
  qualifying class and cannot be registered as one
  (:func:`class_registration_refusal` is the guard every registration
  must pass, and the promotion gate refuses a self-referential class
  on the record even if one were ever written into the list).

Pinning is an adjudication act: the pinner recorded on the record
must validate as a named human on the D-094-1 approvers list under
the ``claim_stage`` actor rules, so an automated identity cannot pin
its own output as evidence (C094-2's rule applied at pin time).

This module reads and writes nothing: it computes over record dicts
and artifact bytes supplied by the caller.
"""
from __future__ import annotations

import hashlib
import re
from datetime import UTC, datetime
from typing import Any

from glossa_lab.claim_stage import is_listed_approver

__all__ = [
    "CANDIDATE_EVIDENCE_FIELDS",
    "REGISTERED_EVIDENCE_CLASSES",
    "EvidenceStandardError",
    "class_registration_refusal",
    "evidence_class_refusal",
    "evidence_pin_refusal",
    "is_loop_output_class",
    "is_registered_evidence_class",
    "normalize_evidence_class",
    "pin_evidence",
    "registered_evidence_classes",
    "sha256_hex",
]


class EvidenceStandardError(ValueError):
    """An evidence pin or registration was refused (fail-closed)."""


#: The Stage 2 evidence fields of an anchor-path candidate record
#: (Spec 094, C094-4/C094-5): the pin and class the promotion gate
#: reads, with the pin's provenance. They are first-class fields of
#: the candidate record, carried by the pipeline's staging write
#: beside Stage 1's ``CANDIDATE_GATE_FIELDS`` — never supplied in the
#: request that asks for a transition. ``evidence_ref`` itself is a
#: Stage 1 gate field; the pin binds to the artifact it names.
CANDIDATE_EVIDENCE_FIELDS: tuple[str, ...] = (
    "evidence_sha256", "evidence_class",
    "evidence_pinned_at", "evidence_pinned_by",
)


def _normalize_class(name: Any) -> str:
    """Normalized class-name form: case-folded, with spaces / hyphens
    folded to underscores (the ``claim_stage`` actor normalization
    shape, applied to class names)."""
    return "_".join(
        str(name or "").strip().lower().replace("-", " ").split()
    ).replace(" ", "_")


def normalize_evidence_class(name: Any) -> str:
    """The normalized form a class name is recorded and matched in."""
    return _normalize_class(name)


#: The registered evidence classes (Spec 094, C094-5): the admissible
#: list as ratified at Stage 2, each entry grounded in the claim's own
#: enumeration. Amended only by a recorded act — a change to this
#: mapping landed through review — never by configuration. A class
#: that :func:`class_registration_refusal` refuses (loop or
#: anchor-path output about the candidate) can never be entered here.
REGISTERED_EVIDENCE_CLASSES: dict[str, str] = {
    "external_corpus_record": (
        "A record in a corpus external to this program's research "
        "loop and anchor path (a published corpus entry, a corpus "
        "snapshot record), cited for the candidate it evidences."),
    "published_concordance_entry": (
        "An entry in a published concordance (a sign-list or "
        "catalogue concordance in print or in a published digital "
        "edition), cited for the candidate it evidences."),
    "independent_expert_record": (
        "A record authored by an expert independent of this program "
        "(correspondence, a review, a published assessment), cited "
        "for the candidate it evidences."),
    "adjudicated_claim_dossier": (
        "The dossier of an adjudicated claim in the program's own "
        "claims ledger — a claim carried through the lifecycle to a "
        "recorded verdict with its evidence trail — cited for the "
        "candidate it evidences. The ledger's adjudication record, "
        "not loop output about the candidate."),
}


def registered_evidence_classes() -> tuple[str, ...]:
    """The registered class names, in registered (sorted) order."""
    return tuple(sorted(REGISTERED_EVIDENCE_CLASSES))


#: Tokens that mark a class name as loop or anchor-path output about
#: the candidate itself. A class whose normalized name contains one of
#: these tokens names the machinery's own product — pipeline outputs,
#: staging and archive files, run syntheses, self-referential
#: attestations — and is not an evidence class (C094-5).
_LOOP_OUTPUT_CLASS_TOKENS: frozenset[str] = frozenset({
    "anchor", "archive", "generated", "internal", "loop", "output",
    "pipeline", "referential", "run", "self", "staging", "synthesis",
    "syntheses",
})


def is_loop_output_class(name: Any) -> bool:
    """True when a class name denotes loop or anchor-path output about
    the candidate itself (fail-closed: an empty name is not one, it is
    simply absent — the class refusal handles absence)."""
    norm = _normalize_class(name)
    if not norm:
        return False
    return bool(set(norm.split("_")) & _LOOP_OUTPUT_CLASS_TOKENS)


def class_registration_refusal(name: Any) -> str | None:
    """The refusal reason for registering *name* as an evidence class,
    or None when the name may be registered.

    This is the guard C094-5 requires: loop or anchor-path output
    about a candidate is not a class and cannot be registered as one
    by configuration — or by any other route, since registration is
    an amendment to :data:`REGISTERED_EVIDENCE_CLASSES` and every
    entry there must pass this guard (the test battery proves the
    registered list satisfies it)."""
    norm = _normalize_class(name)
    if not norm:
        return "an evidence class name may not be empty (Spec 094 C094-5)"
    if is_loop_output_class(norm):
        return (f"evidence class {norm!r} names loop or anchor-path "
                "output about the candidate itself; such output is not "
                "an evidence class and cannot be registered as one "
                "(Spec 094 C094-5)")
    return None


def is_registered_evidence_class(name: Any) -> bool:
    """True when *name* (in any surface form) is on the registered
    list and passes the registration guard."""
    norm = _normalize_class(name)
    return (norm in REGISTERED_EVIDENCE_CLASSES
            and class_registration_refusal(norm) is None)


def sha256_hex(data: bytes) -> str:
    """The SHA-256 of *data*, lowercase hex — the pin form."""
    return hashlib.sha256(data).hexdigest()


_PIN_SHAPE = re.compile(r"^[0-9a-f]{64}$")


def pin_evidence(
    record: dict[str, Any],
    artifact_bytes: bytes,
    *,
    evidence_class: Any,
    pinned_by: Any,
    pinned_at: str | None = None,
) -> dict[str, Any]:
    """Pin an evidence artifact onto a candidate record (C094-4).

    *artifact_bytes* are the bytes of the artifact the record's
    ``evidence_ref`` names, read by the caller at pin time; the pin
    recorded is their SHA-256. The class must be registered and not
    loop output (C094-5); the pinner must validate as a named human
    on the D-094-1 approvers list (an automated identity cannot pin
    its own output as evidence). Returns a NEW record dict carrying
    the evidence fields; the input record is not mutated. Refusals
    raise :class:`EvidenceStandardError` and record nothing.
    """
    refusal = class_registration_refusal(evidence_class)
    if refusal is not None:
        raise EvidenceStandardError(refusal)
    norm_class = _normalize_class(evidence_class)
    if norm_class not in REGISTERED_EVIDENCE_CLASSES:
        raise EvidenceStandardError(
            f"evidence class {norm_class!r} is not on the registered "
            "evidence-class list (Spec 094 C094-5)")
    if not is_listed_approver(str(pinned_by or "")):
        raise EvidenceStandardError(
            f"pinner {pinned_by!r} does not validate as a named human "
            "on the D-094-1 approvers list; pinning is an adjudication "
            "act and automated identities cannot pin evidence "
            "(Spec 094 C094-2, C094-5)")
    pinned = dict(record)
    pinned["evidence_sha256"] = sha256_hex(artifact_bytes)
    pinned["evidence_class"] = norm_class
    pinned["evidence_pinned_at"] = (
        pinned_at or datetime.now(UTC).isoformat(timespec="seconds")
        .replace("+00:00", "Z"))
    pinned["evidence_pinned_by"] = str(pinned_by)
    return pinned


def evidence_pin_refusal(
    candidate: dict[str, Any], artifact_bytes: bytes | None,
) -> str | None:
    """The promotion-gate refusal for a candidate's evidence pin
    (C094-4), or None when the recorded pin verifies.

    Refuses when the record carries no pin, when the pin is not a
    SHA-256 hex digest, when the artifact's bytes cannot be read, or
    when the bytes' hash does not match the pin. Every input is read
    from the candidate record and the artifact it names — a pin that
    exists only in the promote request is an absence here, and the
    endpoint refuses that shape before this check (see
    ``promote_to_anchors``)."""
    pin = candidate.get("evidence_sha256")
    if not isinstance(pin, str) or not pin.strip():
        return ("candidate record carries no evidence pin; promotion "
                "requires an artifact pinned by SHA-256 on the record "
                "at pin time (Spec 094 C094-4)")
    if not _PIN_SHAPE.match(pin.strip().lower()):
        return ("recorded evidence pin is not a SHA-256 hex digest "
                "(Spec 094 C094-4)")
    if artifact_bytes is None:
        return ("the pinned evidence artifact's bytes could not be "
                "read at promotion time (Spec 094 C094-4)")
    if sha256_hex(artifact_bytes) != pin.strip().lower():
        return ("the evidence artifact's bytes do not match the "
                "recorded SHA-256 pin (Spec 094 C094-4)")
    return None


def evidence_class_refusal(candidate: dict[str, Any]) -> str | None:
    """The promotion-gate refusal for a candidate's evidence class
    (C094-5), or None when the recorded class is registered.

    Refuses when the record carries no class, when the class names
    loop or anchor-path output about the candidate itself (never a
    qualifying class, whatever any list says), or when the class is
    absent from the registered list."""
    raw = candidate.get("evidence_class")
    if not isinstance(raw, str) or not raw.strip():
        return ("candidate record carries no evidence class; promotion "
                "requires a class recorded on the candidate record "
                "(Spec 094 C094-5)")
    if is_loop_output_class(raw):
        return (f"recorded evidence class {raw.strip()!r} is loop or "
                "anchor-path output about the candidate itself, which "
                "is not a qualifying evidence class (Spec 094 C094-5)")
    if not is_registered_evidence_class(raw):
        return (f"recorded evidence class {raw.strip()!r} is not on "
                "the registered evidence-class list (Spec 094 C094-5)")
    return None
