def test_cited_records_carry_the_design_facts():
    # The results file: pin and the Arm A primary exactly.
    results_bytes = RESULTS.read_bytes()
    assert hashlib.sha256(results_bytes).hexdigest() == RESULTS_SHA256
    results = json.loads(results_bytes)
    assert results["verdicts"]["arm_a"] == "INCONCLUSIVE"
    arm_a = results["arm_a"]
    assert arm_a["records"] == 1593
    assert arm_a["inscriptions_per_draw"] == 294
    primary = arm_a["primary"]
    assert primary["cells_included"] == 6
    assert primary["median_adj_r2"] == MEDIAN_ADJ
    assert primary["adj_r2_interval_95"] == INTERVAL
    assert primary["share_draws_rejecting"] == SHARE
    assert primary["median_raw_r2"] == 0.022315894493750963
    assert all(
        cell["median_adj_r2"] < 0.01 for cell in arm_a["loso"].values()
    )
    provenance = results["provenance"]
    assert provenance["seed"] == 20261012
    assert provenance["draws"] == 199
    assert provenance["permutations_per_draw"] == 499
    # The margins audit: pin, site totals, cells, sign sets.
    margins_bytes = MARGINS.read_bytes()
    assert hashlib.sha256(margins_bytes).hexdigest() == MARGINS_SHA256
    audit = json.loads(margins_bytes)["arm_a_harappa_excluded"]
    assert audit["site_totals"] == SITE_TOTALS
    assert audit["n_cells_included"] == 6
    assert audit["cells_excluded_lt49"] == {
        "Chanhu-daro|TAB": 2,
        "Dholavira|TAB": 15,
        "Kalibangan|TAB": 3,
        "Lothal|TAB": 2,
    }
    sign_sets = audit["positive_control_sign_sets"]
    assert set(sign_sets) == set(SITE_TOTALS)
    assert all(len(signs) == 10 for signs in sign_sets.values())
    # The pipeline: pin and frozen constants.
    pipeline_bytes = PIPELINE.read_bytes()
    assert hashlib.sha256(pipeline_bytes).hexdigest() == PIPELINE_SHA256
    pipeline = pipeline_bytes.decode("utf-8")
    assert "DRAWS = 199" in pipeline
    assert "PERMS = 499" in pipeline
    assert "N_CELL = 49" in pipeline
    assert "POSITIVE_BOOST = 3.0" in pipeline
    assert "def synthetic_entries" in pipeline
    assert "def run_pipeline_cells" in pipeline
    # The corpus layer, Spec 028 freeze, and anchors: pins only.
    assert hashlib.sha256(CORPUS.read_bytes()).hexdigest() == CORPUS_SHA256
    assert (
        hashlib.sha256(SPEC028_FREEZE.read_bytes()).hexdigest()
        == SPEC028_FREEZE_SHA256
    )
    assert hashlib.sha256(ANCHORS.read_bytes()).hexdigest() == ANCHORS_SHA256
    # The calibration record: the DD-061-13 bracket evidence.
    calibration_bytes = SPEC028_CALIBRATION.read_bytes()
    assert (
        hashlib.sha256(calibration_bytes).hexdigest() == CALIBRATION_SHA256
    )
    calibration = json.loads(calibration_bytes)
    positive = calibration["arm_a"]["positive_control"]
    assert positive["pass"] is True
    assert positive["median_adj_r2"] == 0.023963353007570576
    assert positive["median_adj_r2"] > 0.015
    negative = calibration["arm_a"]["negative_control"]
    assert negative["pass"] is True
    assert negative["median_adj_r2"] < 0.01


