def _find_claim(node, claim_id):
    if isinstance(node, dict):
        if node.get("claim_id") == claim_id:
            return node
        for value in node.values():
            found = _find_claim(value, claim_id)
            if found is not None:
                return found
    elif isinstance(node, list):
        for value in node:
            found = _find_claim(value, claim_id)
            if found is not None:
                return found
    return None


def test_cited_records_carry_the_design_facts():
    # The gazetteer spine: pin, census, cluster count, census sites.
    raw_bytes = GAZETTEER.read_bytes()
    assert hashlib.sha256(raw_bytes).hexdigest() == GAZETTEER_SHA256
    rows = [
        json.loads(line)
        for line in raw_bytes.decode("utf-8").splitlines()
        if line.strip()
    ]
    assert len(rows) == 36
    clusters = {r["program_site_id"] for r in rows}
    assert len(clusters) == 30
    for present in (
        "mohenjo daro", "harappa", "lothal",
        "surkotada", "kalibangan", "banawali",
    ):
        assert present in clusters
    for absent in ("dholavira", "chanhu-daro", "rakhigarhi"):
        assert absent not in clusters
    # The Phase-104 record: UNTESTED under RULE-SITE, census in evidence.
    p104_bytes = PHASE104.read_bytes()
    assert hashlib.sha256(p104_bytes).hexdigest() == PHASE104_SHA256
    entry = _find_claim(json.loads(p104_bytes), CLAIM_ID)
    assert entry is not None
    assert entry["verdict"] == "stays_untested"
    assert entry["rule"] == "RULE-SITE"
    assert "site-typology" in entry["reason"]
    assert "site names only" in entry["reason"]
    distribution_text = entry["evidence"][0]
    for site, count in CENSUS.items():
        assert f"'{site}': {count}" in distribution_text
    assert "CASE_MARKER_SUFFIX" in entry["evidence"][1]
    # The claim file: facts on the live file (Spec 038 form - the
    # freeze-time hash is a definition constant, asserted above;
    # this store is regenerated by the backend suite, so its live
    # whole-file hash is not asserted here).
    claim_doc = json.loads(CLAIM_FILE.read_text(encoding="utf-8"))
    claim_entry = _find_claim(claim_doc, CLAIM_ID)
    assert claim_entry is not None
    assert "arrow sign" in claim_entry["normalized_claim"]
    assert "border enforcement" in claim_entry["normalized_claim"]
    assert claim_entry["proposed_value"].startswith("t\u012br")
    assert claim_entry["falsification_condition"] == (
        "If arrow sign does not cluster at gateway/border sites."
    )
    assert claim_entry["claim_status"] == "untested"
    # The Holdat roles file: pin and the M391 rival record.
    roles_bytes = ROLES.read_bytes()
    assert hashlib.sha256(roles_bytes).hexdigest() == ROLES_SHA256
    roles = json.loads(roles_bytes)
    m391 = roles["roles"]["M391"]
    assert m391["holdatllc_role"] == "CASE_MARKER_SUFFIX"
    assert m391["mapped_to"] == "TERMINAL"
    assert m391["count"] == 193
    assert m391["is_ending"] is True
    assert m391["avg_position"] == 0.6
    # The anchors file: pin only.
    assert (
        hashlib.sha256(ANCHORS.read_bytes()).hexdigest()
        == ANCHORS_SHA256
    )
    # The defect file: pin, five sites, no M391 row.
    defect_bytes = DEFECT_CSV.read_bytes()
    assert hashlib.sha256(defect_bytes).hexdigest() == DEFECT_CSV_SHA256
    reader = list(csv.DictReader(defect_bytes.decode("utf-8").splitlines()))
    assert len(reader) == 271
    site_columns = [k for k in reader[0] if k != "symbol"]
    assert sorted(site_columns) == [
        "Chanhu-daro", "Harappa", "Kalibangan", "Lothal", "Mohenjo-daro",
    ]
    symbols = {r["symbol"] for r in reader}
    assert "M391" not in symbols
    assert "M390" in symbols and "M392" in symbols
    # Spec 047's frozen record: the contract anchor replays, and its
    # spec carries the consumer rule this spec's gate 0.2 applies.
    spec047_freeze = json.loads(
        SPEC047_FREEZE.read_text(encoding="utf-8")
    )
    assert spec047_freeze["digest"] == SPEC047_FREEZE_DIGEST
    assert spec047_freeze["definition"]["design"]["asset_b"]["file"] == (
        "specs/047-roif-ledger-distribution/asset-b/site-functions.jsonl"
    )
    spec047_text = " ".join(
        SPEC047_SPEC.read_text(encoding="utf-8").split()
    )
    assert "Dependents pin the digest" in spec047_text
    assert "step-1 outcome record" in spec047_text


