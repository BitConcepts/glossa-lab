        # The literature registry record: live pin and its facts.
        lit_bytes = (
            REPO / "glossa-indus/literature/documents"
            / f"{document_id}.json"
        ).read_bytes()
        assert hashlib.sha256(lit_bytes).hexdigest() == registry_sha
        lit = json.loads(lit_bytes)
        assert lit["document_id"] == document_id
        assert lit["original_filename"] == filename
        assert lit["file_size_bytes"] == size
