def _find_claim(node, claim_id):
    if isinstance(node, dict):
        if node.get("claim_id") == claim_id:
            return node
        for value in node.values():
            found = _find_claim(value, claim_id)
            if found is not None:
                return found
    elif isinstance(node, list):
        for value in node:
            found = _find_claim(value, claim_id)
            if found is not None:
                return found
    return None


def test_cited_records_carry_the_design_facts():
    # The claim file: facts on the live file (Spec 038 form - the
    # freeze-time hash is a definition constant, asserted above;
    # this store is regenerated by the backend suite, so its live
    # whole-file hash is not asserted here).
    claim_doc = json.loads(CLAIM_FILE.read_text(encoding="utf-8"))
    entry = _find_claim(claim_doc, CLAIM_ID)
    assert entry is not None
    assert entry["normalized_claim"] == "Sign value: 900 / number six"
    assert entry["claim_status"] == "untested"
    assert entry["stage"] == "created"
    assert "which sign, in which published sign list" in (
        entry["not_understood"]
    )
    # The Phase-104 record: UNTESTED under RULE-NUM.
    p104_bytes = PHASE104.read_bytes()
    assert hashlib.sha256(p104_bytes).hexdigest() == PHASE104_SHA256
    p104_entry = _find_claim(json.loads(p104_bytes), CLAIM_ID)
    assert p104_entry is not None
    assert p104_entry["verdict"] == "stays_untested"
    assert p104_entry["rule"] == "RULE-NUM"
    assert "without a stated numbering system" in p104_entry["reason"]
    assert p104_entry["evidence"] == [
        "Crosswalk numeric IDs present in registry: 86"
    ]
    # The registry: pin, 803 rows, the W900-on-P154 trap.
    registry_bytes = REGISTRY.read_bytes()
    assert hashlib.sha256(registry_bytes).hexdigest() == REGISTRY_SHA256
    rows = list(csv.DictReader(registry_bytes.decode("utf-8").splitlines()))
    assert len(rows) == 803
    w900 = [r for r in rows if r["wells_ids"] == "W900"]
    assert len(w900) == 1
    assert w900[0]["sign_id"] == "P154"
    assert "Right parenthesis" in w900[0]["description"]
    assert w900[0]["corpus_freq"] == "93"
    # The held text: pin and the sign-900 material.
    text_bytes = HELD_TEXT.read_bytes()
    assert hashlib.sha256(text_bytes).hexdigest() == HELD_TEXT_SHA256
    text = text_bytes.decode("utf-8")
    assert "702 distinct signs" in text
    assert "Sign 900" in text
    assert "Numerical value of Sign 900" in text
    assert "numerical value of Sign 900 is six" in text
    # The literature record: pin and its recorded facts.
    lit_bytes = LITERATURE.read_bytes()
    assert hashlib.sha256(lit_bytes).hexdigest() == LITERATURE_SHA256
    lit = json.loads(lit_bytes)
    assert lit["file_size_bytes"] == 3565316
    assert lit["checksum_sha256"].startswith("51831ac9")
    assert lit["license_status"] == "unclear"
    # The lane-2 drafts and anchors files: pins only.
    assert hashlib.sha256(LANE2.read_bytes()).hexdigest() == LANE2_SHA256
    assert (
        hashlib.sha256(ANCHORS.read_bytes()).hexdigest()
        == ANCHORS_SHA256
    )


FREEZE_STAMPS = [
    "20261021T104301Z",
    "20261021T104301Z",
    "20261021T104302Z",
]

CORRECTNESS_CATEGORIES = {
    "coverage_gap",
    "contradiction",
    "assumption_unvalidated",
    "ambiguous_requirement",
    "independence_unmodeled",
}


def test_freeze_hook_artifacts_record_the_pass():
    aee_dir = SPEC / "aee"
    for phase, stamp in zip(
        ("after_specify", "after_plan", "after_tasks"),
        FREEZE_STAMPS,
    ):
        record = json.loads(
            (aee_dir / f"aee-{phase}-{stamp}.json").read_text(
                encoding="utf-8")
        )
        failures = [
            f for c in record["claims"] for f in c["failures"]
        ]
        assert failures, phase
        assert {f["category"] for f in failures} <= {"draft_cap"}, phase
        assert not [
            f for f in failures
            if f["category"] in CORRECTNESS_CATEGORIES
        ], phase
        confidences = [c["confidence"] for c in record["claims"]]
        assert min(confidences) >= 0.70, phase
