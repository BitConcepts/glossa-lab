def _sha256_bytes(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def _sha256(path: Path) -> str:
    return _sha256_bytes(path.read_bytes())


def _normalise(name: str) -> str:
    """Spec section 5.1 (Spec 047 section 6.1 form):
    lowercase, whitespace and punctuation collapsed.
    No fuzzy matching, no hand assignment."""
    lowered = name.lower()
    spaced = re.sub(r"[^\w\s]", " ", lowered, flags=re.UNICODE)
    return " ".join(spaced.split())


def _find_claim(node, claim_id):
    if isinstance(node, dict):
        if node.get("claim_id") == claim_id:
            return node
        for value in node.values():
            found = _find_claim(value, claim_id)
            if found is not None:
                return found
    elif isinstance(node, list):
        for value in node:
            found = _find_claim(value, claim_id)
            if found is not None:
                return found
    return None


class Closure(Exception):
    """A frozen gate closure: carries the outcome class
    and the gate record to write."""

    def __init__(self, outcome: str, gate: str, observed: str):
        super().__init__(f"{gate}: {observed}")
        self.outcome = outcome
        self.gate = gate
        self.observed = observed


