"""Spec 087 Stage S4 — manual conformance tests (T402).

Claims covered:
  C087-8  The manual's node reference is the palette set,
          mechanically: the generated reference (user-manual block
          and the HelpView data module) lists exactly the palette
          set with each node's category, ports, and params as the
          registry states them; regeneration diffs clean in both
          directions.
  C087-9  No manual names a node or experiment that does not
          exist: none of the 10 phantom node names of census
          Table 3 appears in any manual surface, and USER_GUIDE's
          experiments list is generated from the graph files on
          disk (27 today), neither more nor fewer.

The Spec 084 pattern: committed generated output + a test that
regenerates and diffs. A failure means drift in one direction or
the other — a hand edit inside a generated block, a registry
change that was not regenerated, or a phantom name re-entering
prose. The fix is always to regenerate
(`python tools/manual/generate_node_reference.py`) or to correct
the prose — never to edit the generated bytes by hand.
"""

from __future__ import annotations

import json
import re
from pathlib import Path

from glossa_lab import manual_generate as mg
from glossa_lab.experiment_graph import ATOMIC_NODES

_REPO = Path(__file__).resolve().parents[2]

# The 10 phantom node names of census Table 3
# (specs/087-node-system-tightening/records/census-evidence.md):
# node names the manuals listed that do not exist in the registry.
PHANTOM_NODE_NAMES = [
    "CorpusLoader",
    "EntropyAnalyzer",
    "MappingInference",
    "AnchorInjector",
    "ConsistencyEvaluator",
    "AnchorAccuracyEvaluator",
    "RandomBaselineComparator",
    "JSONReportWriter",
    "MarkdownReportWriter",
    "PDFReportWriter",
]

_MANUAL_SURFACES = [
    "docs/user-manual.md",
    "docs/USER_GUIDE.md",
    "frontend/src/components/HelpView.tsx",
    "frontend/src/components/help/nodeReference.generated.ts",
]


def _surface(rel: str) -> str:
    return (_REPO / rel).read_text(encoding="utf-8")


# ── C087-8: regeneration diffs clean, both directions ───────────────────────


def test_generated_surfaces_match_fresh_build():
    drifted = mg.check_outputs(_REPO)
    assert not drifted, (
        "generated manual surfaces drifted from the live registry: "
        f"{drifted} — regenerate with "
        "tools/manual/generate_node_reference.py"
    )


def test_helpview_module_lists_exactly_the_palette_set():
    module = _surface(mg.HELPVIEW_MODULE_REL)
    match = re.search(
        r"export const NODE_REFERENCE: NodeReferenceEntry\[\] = (\[.*?\]);\n",
        module,
        re.DOTALL,
    )
    assert match, "NODE_REFERENCE array not found in the generated module"
    entries = json.loads(match.group(1))
    listed = [e["id"] for e in entries]
    palette = sorted(d.id for d in ATOMIC_NODES.values() if not d.legacy)
    assert sorted(listed) == palette
    assert len(listed) == len(set(listed)), "duplicate ids in the reference"


def test_user_manual_block_lists_exactly_the_palette_set():
    manual = _surface(mg.USER_MANUAL_REL)
    begin = manual.index(mg.BEGIN_NODE_REFERENCE)
    end = manual.index(mg.END_NODE_REFERENCE)
    block = manual[begin:end]
    listed = re.findall(r"^\*\*`([^`]+)` — ", block, re.MULTILINE)
    palette = sorted(d.id for d in ATOMIC_NODES.values() if not d.legacy)
    assert sorted(listed) == palette


def test_node_reference_carries_registry_ports_and_params():
    """Spot-weld the full-model comparison: one node's block entry and
    module entry must state the registry's own ports and params."""
    from glossa_lab.experiment_graph import ATOMIC_NODES as nodes

    model, _counts = mg.build_node_model()
    by_id = {n["id"]: n for n in model}
    for probe in ("SADecipher", "TokenFilter", "CorpusReader"):
        reg = nodes[probe]
        entry = by_id[probe]
        assert [p["name"] for p in entry["inputs"]] == [
            p["name"] for p in reg.inputs
        ]
        assert [p["name"] for p in entry["outputs"]] == [
            p["name"] for p in reg.outputs
        ]
        reg_params = set((reg.params_schema or {}).get("properties", {}))
        assert {p["name"] for p in entry["params"]} == reg_params
        assert entry["category"] == reg.category


def test_helpview_renders_the_generated_module():
    """The in-app reference must render the generation, not a copy."""
    helpview = _surface("frontend/src/components/HelpView.tsx")
    assert "nodeReference.generated" in helpview
    assert "NODE_REFERENCE" in helpview
    # The stale hand-kept reference heading set is gone: the section is
    # built from the module, so no per-node hand entries remain.
    assert "Complete Node Reference" in helpview  # the generated heading


# ── C087-9: absence — the phantom names stay out ────────────────────────────


def test_no_phantom_node_names_in_manual_surfaces():
    offenders: dict[str, list[str]] = {}
    for rel in _MANUAL_SURFACES:
        text = _surface(rel)
        for name in PHANTOM_NODE_NAMES:
            if re.search(rf"\b{re.escape(name)}\b", text):
                offenders.setdefault(rel, []).append(name)
    assert not offenders, f"phantom node names in manual surfaces: {offenders}"


# ── C087-9: USER_GUIDE's experiment list is the graph files on disk ─────────


def test_user_guide_experiments_match_graph_files_on_disk():
    guide = _surface(mg.USER_GUIDE_REL)
    begin = guide.index(mg.BEGIN_EXPERIMENTS)
    end = guide.index(mg.END_EXPERIMENTS)
    block = guide[begin:end]
    listed = re.findall(r"^\| `([^`]+)` \|", block, re.MULTILINE)
    graphs_dir = _REPO / mg.GRAPHS_REL
    on_disk = sorted(p.stem for p in graphs_dir.glob("*.json"))
    assert sorted(listed) == on_disk
    assert len(listed) == len(on_disk) == 27
